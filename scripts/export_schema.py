from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateTable
from app.db import Base
from app import models  # noqa: F401

parts = ["-- Generated by scripts/export_schema.py. Run scripts/setup_db.py to apply it.\n"]
for t in Base.metadata.sorted_tables:
    parts.append(str(CreateTable(t).compile(dialect=postgresql.dialect())).strip() + ";\n")
with open("sql/audit_triggers.sql") as f:
    parts.append("\n" + f.read())
with open("sql/schema.sql", "w") as f:
    f.write("\n".join(parts))